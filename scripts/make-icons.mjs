/*
 * ساخت آیکون‌ها (SVG → PNG با sharp)
 * -----------------------------------
 *  build/icon.png          ۱۰۲۴px — آیکون برنامه برای electron-builder (ico/icns خودکار ساخته می‌شه)
 *  assets/icon.png         ۵۱۲px  — آیکون پنجره (ویندوز/لینوکس)
 *  assets/tray.png         ۶۴px   — آیکون رنگی tray
 *  assets/trayTemplate.png ۴۴px   — آیکون template تک‌رنگ مک (با scaleFactor: 2 لود می‌شه)
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import sharp from 'sharp';

mkdirSync('build', { recursive: true });
mkdirSync('assets', { recursive: true });

// ساعت‌شمار با حلقه‌ی پیشرفت روی زمینه‌ی teal
const appIcon = (bg = true) => `
<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 64 64" fill="none">
  ${bg ? '<rect width="64" height="64" rx="15" fill="#0e9f8e"/>' : ''}
  <circle cx="32" cy="35" r="17" stroke="rgba(255,255,255,.28)" stroke-width="5"/>
  <path d="M32 18 A17 17 0 1 1 15.4 39.2" stroke="#fff" stroke-width="5" stroke-linecap="round"/>
  <path d="M32 35 L32 26" stroke="#fff" stroke-width="4" stroke-linecap="round"/>
  <rect x="28" y="8" width="8" height="5" rx="2" fill="#fff"/>
</svg>`;

// نسخه‌ی template: فقط سیاه + شفافیت (سیستم‌عامل خودش رنگ می‌کنه)
const templateIcon = `
<svg xmlns="http://www.w3.org/2000/svg" width="44" height="44" viewBox="0 0 64 64" fill="none">
  <circle cx="32" cy="35" r="19" stroke="#000" stroke-opacity=".35" stroke-width="6"/>
  <path d="M32 16 A19 19 0 1 1 13.5 40.5" stroke="#000" stroke-width="6" stroke-linecap="round"/>
  <path d="M32 35 L32 25" stroke="#000" stroke-width="5" stroke-linecap="round"/>
  <rect x="27" y="5" width="10" height="6" rx="2.5" fill="#000"/>
</svg>`;

const render = (svg, size, file) =>
  sharp(Buffer.from(svg)).resize(size, size).png().toFile(file);

await render(appIcon(true), 1024, 'build/icon.png');
await render(appIcon(true), 512, 'assets/icon.png');
await render(appIcon(true), 64, 'assets/tray.png');
await render(templateIcon, 44, 'assets/trayTemplate.png');
writeFileSync('assets/README.txt', 'Generated by scripts/make-icons.mjs — do not edit by hand.\n');
console.log('icons written to build/ and assets/');
